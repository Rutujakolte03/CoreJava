class Quetions {
    public static void main(String[] args) {
        // For primitive data type (int), you can initialize it with a number.
        int a = 10;
        System.out.println(a);

        // For reference types (Integer), you can assign null.
        Integer b = null; // Integer is an object type, not primitive.
        System.out.println(b); // This will print 'null'
    }
}
